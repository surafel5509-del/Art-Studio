/**
 * Release signing is read from `keystore.properties` (never committed) or from
 * environment variables, so CI can build a signed AAB without secrets in the repo.
 * When nothing is configured the release build falls back to the debug signing
 * config so that `assembleRelease` still produces an installable artifact.
 */
val keystorePropertiesFile = rootProject.file("keystore.properties")
val keystoreProperties = Properties().apply {
    if (keystorePropertiesFile.exists()) keystorePropertiesFile.inputStream().use { load(it) }
}
fun signingValue(key: String, env: String): String? =
    keystoreProperties.getProperty(key) ?: System.getenv(env)

val releaseStoreFile = signingValue("storeFile", "ARTFORGE_KEYSTORE_PATH")
val releaseStorePassword = signingValue("storePassword", "ARTFORGE_KEYSTORE_PASSWORD")
val releaseKeyAlias = signingValue("keyAlias", "ARTFORGE_KEY_ALIAS")
val releaseKeyPassword = signingValue("keyPassword", "ARTFORGE_KEY_PASSWORD")
val hasReleaseSigning = releaseStoreFile != null && releaseStorePassword != null &&
    releaseKeyAlias != null && releaseKeyPassword != null

